export const generateFeedData = (totalCount = 30): FeedItem[] => {
  const feed: FeedItem[] = [];
  let videoIndex = 0;
  let adIndex = 0;

  for (let i = 0; i < totalCount; i += 1) {
    const position = i + 1;
    if (position % 5 === 0) {
      feed.push({
        id: `ad-${position}`,
        type: 'ad',
        ...MOCK_ADS[adIndex % MOCK_ADS.length],
      } as FeedItem);
      adIndex += 1;
    } else {
      const video = RAW_VIDEOS[videoIndex % RAW_VIDEOS.length];
      feed.push({
        id: `video-${position}`,
        type: 'video',
        ...video,
      } as FeedItem);
      videoIndex += 1;
    }
  }

  return feed;
};
